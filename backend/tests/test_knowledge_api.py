def test_sources_list_detail_delete(client, auth, project):
    pid = project["id"]
    sid = _upload(client, auth, pid, "notes.md", LEAK_DOC.encode()).json()["source"]["id"]

    listed = client.get(f"/projects/{pid}/sources", headers=auth).json()
    assert [s["id"] for s in listed] == [sid]
    assert listed[0]["preview"] and listed[0]["retrieved_at"]

    detail = client.get(f"/projects/{pid}/sources/{sid}", headers=auth).json()
    assert len(detail["passages"]) == detail["chunk_count"] >= 2

    assert client.delete(f"/projects/{pid}/sources/{sid}", headers=auth).status_code == 204
    assert client.get(f"/projects/{pid}/sources", headers=auth).json() == []
    assert client.get(f"/projects/{pid}/sources/{sid}", headers=auth).status_code == 404


def test_search_modes_and_citations(client, auth, project, db_session):
    _public_doc(db_session, "Tutoring market", TUTOR_DOC)
    pid = project["id"]
    _upload(client, auth, pid, "notes.md", LEAK_DOC.encode())

    for mode in ("hybrid", "vector", "keyword"):
        r = client.post(f"/projects/{pid}/search", json={"query": "solar gateway leak alerts", "mode": mode},
                        headers=auth)
        assert r.status_code == 200, r.text
        passages = r.json()["passages"]
        assert passages, mode
        assert passages[0]["title"] == "LeakGuard field notes", mode
        assert passages[0]["kb"] == "C"

    body = client.post(f"/projects/{pid}/search", json={"query": "affordable peer tutors reviews"},
                       headers=auth).json()
    top = body["passages"][0]
    assert top["title"] == "Tutoring market" and top["url"].startswith("https://example.org/")
    assert body["evidence_block"].startswith("[E1] (source: Tutoring market")
    # filters
    only_c = client.post(f"/projects/{pid}/search", json={"query": "affordable peer tutors", "kbs": ["C"]},
                         headers=auth).json()["passages"]
    assert all(p["kb"] == "C" for p in only_c)
    assert client.post(f"/projects/{pid}/search", json={"query": "x"}, headers=auth).status_code == 422


