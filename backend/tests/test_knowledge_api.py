"""Ingestion, uploads, sources, search and KB-C isolation through the API (DB tests)."""

from __future__ import annotations

import io

from sqlalchemy import func, select, text

from app.models.research import ResearchChunk, ResearchSource
from app.services.knowledge.ingest import DocumentIn, ingest_document
from tests.conftest import register_and_login

LEAK_DOC = (
    "# LeakGuard field notes\n\n"
    + " ".join(
        f"Note {i}: our LoRa leak sensors in apartment risers detected pressure drops and the "
        "solar gateway alerted the building manager by SMS within seconds."
        for i in range(60)
    )
)
TUTOR_DOC = " ".join(
    f"Interview {i}: university students said affordable peer tutors and verified reviews matter "
    "more than price comparison when they book exam preparation sessions."
    for i in range(40)
)


def _upload(client, headers, project_id, name, body, mime="text/plain"):
    return client.post(
        f"/projects/{project_id}/documents",
        files={"file": (name, io.BytesIO(body), mime)},
        headers=headers,
    )


def _public_doc(db, title, body, kb="A", category="business"):
    result = ingest_document(
        db,
        DocumentIn(
            title=title, text=body, kb=kb, url=f"https://example.org/{title.replace(' ', '-')}",
            source_type="wikipedia", publisher="Example", licence_note="CC BY-SA 4.0",
            attribution="Example contributors", category=category,
        ),
    )
    db.commit()
    return result


def test_ingest_pipeline_chunks_embeds_and_dedupes(db_session):
    first = _public_doc(db_session, "LoRa", LEAK_DOC, kb="B", category="technology")
    assert first.status == "created" and first.chunks >= 2
    chunks = db_session.scalars(
        select(ResearchChunk).where(ResearchChunk.source_id == first.source_id)
        .order_by(ResearchChunk.chunk_index)
    ).all()
    assert [c.chunk_index for c in chunks] == list(range(len(chunks)))
    assert all(c.kb == "B" and c.user_id is None for c in chunks)
    assert chunks[0].content.startswith("LeakGuard field notes:")  # heading path kept
    embedded = db_session.execute(
        text("SELECT count(*) FROM embeddings e JOIN research_chunks c ON c.id = e.chunk_id "
             "WHERE c.source_id = :s"), {"s": first.source_id}
    ).scalar()
    assert embedded == len(chunks)
    # tsvector is generated by PostgreSQL
    assert db_session.execute(
        text("SELECT count(*) FROM research_chunks WHERE source_id = :s AND tsv @@ "
             "to_tsquery('english', 'gateway')"), {"s": first.source_id}
    ).scalar() > 0

    again = _public_doc(db_session, "LoRa copy", LEAK_DOC.upper(), kb="B")
    assert again.status == "duplicate" and again.source_id == first.source_id


