def test_isolation_between_users(client, auth, project, db_session):
    """User B can never see or retrieve user A's KB-C data (AI_DESIGN 10.2: 100%)."""
    pid_a = project["id"]
    _upload(client, auth, pid_a, "secret.md", LEAK_DOC.encode())
    sid_a = client.get(f"/projects/{pid_a}/sources", headers=auth).json()[0]["id"]
    _public_doc(db_session, "Tutoring market", TUTOR_DOC)

    bob = register_and_login(client, "bob@example.com")
    pid_b = client.post("/projects", json={"title": "Bob idea", "idea_text": "A leak detection product "
                        "for apartments with LoRa sensors and solar gateways."}, headers=bob).json()["id"]

    # direct access: 404 everywhere
    assert client.get(f"/projects/{pid_a}/sources", headers=bob).status_code == 404
    assert client.get(f"/projects/{pid_b}/sources/{sid_a}", headers=bob).status_code == 404
    assert client.delete(f"/projects/{pid_b}/sources/{sid_a}", headers=bob).status_code == 404
    assert client.post(f"/projects/{pid_a}/search", json={"query": "solar gateway"}, headers=bob).status_code == 404
    assert _upload(client, bob, pid_a, "x.md", TUTOR_DOC.encode()).status_code == 404

    # retrieval: every mode, even when asking for KB-C explicitly
    for mode in ("hybrid", "vector", "keyword"):
        for kbs in (None, ["C"], ["A", "B", "C"]):
            payload = {"query": "LoRa leak sensors solar gateway building manager", "mode": mode, "k": 20}
            if kbs:
                payload["kbs"] = kbs
            got = client.post(f"/projects/{pid_b}/search", json=payload, headers=bob).json()["passages"]
            assert all(p["kb"] != "C" for p in got), (mode, kbs)
            assert all(p["source_id"] != sid_a for p in got), (mode, kbs)

    # a second project of the same user A does not see project A's KB-C either
    pid_a2 = client.post("/projects", json={"title": "Second", "idea_text": "Another idea about "
                         "solar gateways and leak sensors in buildings."}, headers=auth).json()["id"]
    got = client.post(f"/projects/{pid_a2}/search", json={"query": "solar gateway leak", "k": 20},
                      headers=auth).json()["passages"]
    assert all(p["kb"] != "C" for p in got)

    # public KB-A stays visible to everyone
    pub = client.post(f"/projects/{pid_b}/search", json={"query": "affordable peer tutors"}, headers=bob).json()
    assert pub["passages"][0]["title"] == "Tutoring market"


def test_deleting_project_removes_its_knowledge(client, auth, project, db_session):
    pid = project["id"]
    _upload(client, auth, pid, "notes.md", LEAK_DOC.encode())
    assert client.delete(f"/projects/{pid}", headers=auth).status_code == 204
    assert db_session.scalar(select(func.count()).select_from(ResearchSource).where(ResearchSource.kb == "C")) == 0
    assert db_session.scalar(select(func.count()).select_from(ResearchChunk).where(ResearchChunk.kb == "C")) == 0


def test_knowledge_stats(client, auth, project, db_session):
    _public_doc(db_session, "Tutoring market", TUTOR_DOC)
    _upload(client, auth, project["id"], "notes.md", LEAK_DOC.encode())
    stats = client.get("/knowledge/stats", headers=auth).json()
