// Regenerates app/icon.svg (the favicon) from the PATHS in components/brand/Logo.tsx.
// Run from frontend/:  node scripts/gen-icon.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("components/brand/Logo.tsx", "utf8");
const start = src.indexOf("const PATHS = [");
const block = src.slice(start, src.indexOf("];", start));
const paths = [...block.matchAll(/^\s*"([^"]+)",?$/gm)].map((m) => m[1]);
if (paths.length === 0) throw new Error("No PATHS found in Logo.tsx");

// Same colours as --if-brand-copper / --if-brand-teal (light theme) in app/globals.css.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" fill="none" stroke-width="5" stroke-linecap="round" stroke-linejoin="round">
  <!-- Generated by scripts/gen-icon.mjs from components/brand/Logo.tsx. Do not edit by hand. -->
  <defs>
    <linearGradient id="g" x1="30" y1="6" x2="72" y2="96" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#c88a6a"/>
      <stop offset=".42" stop-color="#c88a6a"/>
      <stop offset=".78" stop-color="#6fa8a3"/>
      <stop offset="1" stop-color="#6fa8a3"/>
    </linearGradient>
  </defs>
  <g stroke="url(#g)">
${paths.map((d) => `    <path d="${d}"/>`).join("\n")}
  </g>
</svg>
`;
writeFileSync("app/icon.svg", svg);
console.log(`app/icon.svg written (${paths.length} paths)`);
